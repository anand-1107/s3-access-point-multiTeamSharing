from fastapi import APIRouter, HTTPException, Request
from app.models import TeamConfig

router = APIRouter(prefix="/s3-access", tags=["Team Operations"])


def service(request: Request):
    return request.app.state.team_service


@router.post("/add-team", summary="Add Team", description="Create or reconcile team S3 access. Policies are generated by the service; raw policy JSON is not accepted.")
def add_team(body: TeamConfig, request: Request):
    try:
        return service(request).configure(body)
    except RuntimeError as exc:
        message = str(exc)
        status = 403 if "AccessDenied" in message or "403" in message else 502
        raise HTTPException(status_code=status, detail=message)


@router.put("/update-team", summary="Update Team", description="Update and reconcile a team's prefix or permissions.")
def update_team(body: TeamConfig, request: Request):
    try:
        return service(request).configure(body)
    except RuntimeError as exc:
        message = str(exc)
        status = 403 if "AccessDenied" in message or "403" in message else 502
        raise HTTPException(status_code=status, detail=message)


@router.get("/get-team/{team}", summary="Get Team")
def get_team(team: str, request: Request):
    record = service(request).get_team(team)
    if not record:
        raise HTTPException(status_code=404, detail="Team configuration not found")
    return record


@router.get("/list-teams", summary="List Teams")
def list_teams(request: Request):
    return {"teams": service(request).list_teams()}


@router.get("/get-team-access/{team}", summary="Get Team Access")
def get_access(team: str, request: Request):
    try:
        record = service(request).access(team)
    except PermissionError as exc:
        raise HTTPException(status_code=409, detail=str(exc))
    except RuntimeError as exc:
        raise HTTPException(status_code=502, detail=str(exc))
    if not record:
        raise HTTPException(status_code=404, detail="Team configuration not found")
    return record


@router.delete("/remove-team/{team}", summary="Remove Team")
def remove_team(team: str, request: Request):
    try:
        return service(request).delete(team)
    except LookupError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    except PermissionError as exc:
        raise HTTPException(status_code=409, detail=str(exc))
    except RuntimeError as exc:
        raise HTTPException(status_code=502, detail=str(exc))
